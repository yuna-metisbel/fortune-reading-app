def build_personal_user_prompt(
    nickname: str,
    birth_date: str,
    birth_time: str | None,
    birth_place: str | None,
    gender: str | None,
    blood_type: str | None,
    theme: str | None,
) -> str:
    """個人リーディング用のユーザープロンプトを構築する。

    Args:
        nickname: 占い対象者のニックネーム
        birth_date: 生年月日（例: "1990-03-15"）
        birth_time: 生まれた時刻（例: "14:30"）、不明の場合は None
        birth_place: 出生地（例: "東京都渋谷区"）、不明の場合は None
        gender: 性別（例: "女性"）、不明の場合は None
        blood_type: 血液型（例: "A"）、不明の場合は None
        theme: 特に知りたいテーマや悩み、None の場合は省略

    Returns:
        フォーマット済みのユーザープロンプト文字列
    """
    def _val(v: str | None) -> str:
        return v if v is not None else "不明"

    lines = [
        f"【占い対象】{nickname}",
        "",
        "## 基本情報",
        f"- 生年月日：{birth_date}",
        f"- 生まれた時刻：{_val(birth_time)}",
        f"- 出生地：{_val(birth_place)}",
        f"- 性別：{_val(gender)}",
        f"- 血液型：{_val(blood_type)}",
    ]

    if theme:
        lines += [
            "",
            "## 特に知りたいテーマ・相談内容",
            theme,
        ]

    lines += [
        "",
        "上記の情報をもとに、指定のフォーマットで詳細なリーディングを行ってください。",
    ]

    return "\n".join(lines)


def build_compatibility_user_prompt(
    person1_nickname: str,
    person1_birth_date: str,
    person1_birth_time: str | None,
    person1_birth_place: str | None,
    person1_gender: str | None,
    person1_blood_type: str | None,
    person2_nickname: str,
    person2_birth_date: str,
    person2_birth_time: str | None,
    person2_birth_place: str | None,
    person2_gender: str | None,
    person2_blood_type: str | None,
    relationship_type: str | None,
    met_date: str | None,
    theme: str | None,
) -> str:
    """相性リーディング用のユーザープロンプトを構築する。

    Args:
        person1_nickname: 1人目のニックネーム
        person1_birth_date: 1人目の生年月日
        person1_birth_time: 1人目の生まれた時刻、不明の場合は None
        person1_birth_place: 1人目の出生地、不明の場合は None
        person1_gender: 1人目の性別、不明の場合は None
        person1_blood_type: 1人目の血液型、不明の場合は None
        person2_nickname: 2人目のニックネーム
        person2_birth_date: 2人目の生年月日
        person2_birth_time: 2人目の生まれた時刻、不明の場合は None
        person2_birth_place: 2人目の出生地、不明の場合は None
        person2_gender: 2人目の性別、不明の場合は None
        person2_blood_type: 2人目の血液型、不明の場合は None
        relationship_type: 関係性の種類（例: "恋人候補", "既婚", "友人"）、None の場合は省略
        met_date: 出会った時期（例: "2023年春"）、None の場合は省略
        theme: 特に知りたいテーマや悩み、None の場合は省略

    Returns:
        フォーマット済みのユーザープロンプト文字列
    """
    def _val(v: str | None) -> str:
        return v if v is not None else "不明"

    lines = [
        f"【相性リーディング】{person1_nickname} と {person2_nickname}",
        "",
        f"## {person1_nickname}（1人目）の情報",
        f"- 生年月日：{person1_birth_date}",
        f"- 生まれた時刻：{_val(person1_birth_time)}",
        f"- 出生地：{_val(person1_birth_place)}",
        f"- 性別：{_val(person1_gender)}",
        f"- 血液型：{_val(person1_blood_type)}",
        "",
        f"## {person2_nickname}（2人目）の情報",
        f"- 生年月日：{person2_birth_date}",
        f"- 生まれた時刻：{_val(person2_birth_time)}",
        f"- 出生地：{_val(person2_birth_place)}",
        f"- 性別：{_val(person2_gender)}",
        f"- 血液型：{_val(person2_blood_type)}",
    ]

    if relationship_type or met_date:
        lines += ["", "## 二人の関係について"]
        if relationship_type:
            lines.append(f"- 関係性：{relationship_type}")
        if met_date:
            lines.append(f"- 出会った時期：{met_date}")

    if theme:
        lines += [
            "",
            "## 特に知りたいテーマ・相談内容",
            theme,
        ]

    lines += [
        "",
        "上記の情報をもとに、指定のフォーマットで詳細な相性リーディングを行ってください。",
    ]

    return "\n".join(lines)
