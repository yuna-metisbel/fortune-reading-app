def build_personal_user_prompt(
    nickname: str,
    birth_date: str,
    birth_time: str | None,
    birth_place: str | None,
    gender: str | None,
    blood_type: str | None,
    theme: str | None,
    rokusei_result: dict | None = None,
    shichusuimei_result: dict | None = None,
    numerology_result: dict | None = None,
) -> str:
    """個人リーディング用のユーザープロンプトを構築する。

    Args:
        nickname: 占い対象者のニックネーム
        birth_date: 生年月日（例: "1990-03-15"）
        birth_time: 生まれた時刻（例: "14:30"）、不明の場合は None
        birth_place: 出生地（例: "東京都渋谷区"）、不明の場合は None
        gender: 性別（例: "女性"）、不明の場合は None
        blood_type: 血液型（例: "A"）、不明の場合は None
        theme: 特に知りたいテーマや悩み、None の場合は省略
        rokusei_result: 六星占術の計算結果 dict、None の場合は省略
        shichusuimei_result: 四柱推命の年柱計算結果 dict、None の場合は省略
        numerology_result: 数秘術の計算結果 dict、None の場合は省略

    Returns:
        フォーマット済みのユーザープロンプト文字列
    """
    def _val(v: str | None) -> str:
        return v if v is not None else "不明"

    lines = [
        f"【占い対象】{nickname}",
        "",
        "## 基本情報",
        f"- 生年月日：{birth_date}",
        f"- 生まれた時刻：{_val(birth_time)}",
        f"- 出生地：{_val(birth_place)}",
        f"- 性別：{_val(gender)}",
        f"- 血液型：{_val(blood_type)}",
    ]

    if rokusei_result:
        lines.append(f"- 六星占術：{rokusei_result['star_full']}")

    if shichusuimei_result:
        lines.append(
            f"- 四柱推命（年柱）：{shichusuimei_result['pillar']}"
            f"（{shichusuimei_result['stem_element']}の{shichusuimei_result['yinyang']}）"
        )

    if numerology_result:
        lines.append(f"- 数秘術ライフパスナンバー：{numerology_result['description']}")

    if theme:
        lines += [
            "",
            "## 特に知りたいテーマ・相談内容",
            theme,
        ]

    lines += [
        "",
        "上記の情報をもとに、指定のフォーマットで詳細なリーディングを行ってください。",
    ]

    if rokusei_result:
        lines += [
            "",
            "【重要】六星占術の運命星は上記の通り正確に算出済みです。"
            "リーディング内では必ずこの結果をそのまま使用してください。"
            "独自に再計算しないでください。",
        ]

    return "\n".join(lines)


